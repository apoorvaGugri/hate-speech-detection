"""Exploratory data analysis on the RAW dataset.

    python -m src.data.eda

Writes reports/eda_summary.md and figures to reports/figures/. Only aggregate
statistics are written - no tweet text - so the outputs are safe to commit.
"""
from __future__ import annotations

import sys

import pandas as pd

from src.constants import ID2LABEL
from src.data.load import VOTE_COLUMNS, load_raw
from src.data.split import clean_and_deduplicate
from src.evaluation.plots import plot_class_distribution, plot_length_distribution
from src.preprocessing.text_cleaner import MENTION_RE, URL_RE
from src.utils.config import get_dir, load_config, resolve_path
from src.utils.logger import get_logger

log = get_logger(__name__)


def compute_eda(df: pd.DataFrame) -> dict:
    """Return all EDA statistics as plain Python objects."""
    counts = df["label"].value_counts().sort_index()
    total = int(len(df))
    summary: dict = {
        "rows": total,
        "class_counts": {ID2LABEL[i]: int(counts.get(i, 0)) for i in ID2LABEL},
        "class_share_pct": {ID2LABEL[i]: round(100 * counts.get(i, 0) / total, 2) for i in ID2LABEL},
    }
    majority, minority = counts.max(), max(counts.min(), 1)
    summary["imbalance_ratio"] = round(float(majority / minority), 1)

    words = df["text"].str.split().str.len()
    chars = df["text"].str.len()
    summary["length_words"] = {
        "mean": round(float(words.mean()), 1),
        "median": float(words.median()),
        "p95": float(words.quantile(0.95)),
        "max": int(words.max()),
    }
    summary["length_chars_mean"] = round(float(chars.mean()), 1)
    summary["words_mean_by_class"] = {
        ID2LABEL[i]: round(float(words[df["label"] == i].mean()), 1) for i in ID2LABEL if (df["label"] == i).any()
    }
    summary["pct_with_url"] = round(100 * float(df["text"].str.contains(URL_RE).mean()), 1)
    summary["pct_with_mention"] = round(100 * float(df["text"].str.contains(MENTION_RE).mean()), 1)
    summary["pct_retweets"] = round(100 * float(df["text"].str.contains(r"\bRT\b").mean()), 1)

    # Annotator agreement: share of annotators who voted for the majority label.
    if all(c in df.columns for c in VOTE_COLUMNS) and "count" in df.columns:
        agreement = df[VOTE_COLUMNS].max(axis=1) / df["count"].clip(lower=1)
        summary["annotators_per_tweet_mean"] = round(float(df["count"].mean()), 2)
        summary["pct_unanimous"] = round(100 * float((agreement == 1).mean()), 1)
        summary["mean_agreement_by_class"] = {
            ID2LABEL[i]: round(float(agreement[df["label"] == i].mean()), 3)
            for i in ID2LABEL
            if (df["label"] == i).any()
        }

    _, dedup_stats = clean_and_deduplicate(df)
    summary["cleaning"] = dedup_stats
    return summary


def write_report(summary: dict, path) -> None:
    lines = ["# EDA summary (generated by `python -m src.data.eda`)", ""]
    lines += [f"- Rows: **{summary['rows']}**", f"- Imbalance ratio (largest / smallest class): **{summary['imbalance_ratio']}**", ""]
    lines += ["| Class | Tweets | Share % |", "|---|---:|---:|"]
    for name, count in summary["class_counts"].items():
        lines.append(f"| {name} | {count} | {summary['class_share_pct'][name]} |")
    lines += ["", "## Text length (words)", ""]
    lines += [f"- {k}: {v}" for k, v in summary["length_words"].items()]
    lines += [f"- mean words, {k}: {v}" for k, v in summary["words_mean_by_class"].items()]
    lines += ["", "## Twitter artefacts", ""]
    lines += [
        f"- Tweets containing a URL: {summary['pct_with_url']}%",
        f"- Tweets containing an @mention: {summary['pct_with_mention']}%",
        f"- Tweets containing the RT marker: {summary['pct_retweets']}%",
    ]
    if "pct_unanimous" in summary:
        lines += ["", "## Annotator agreement", ""]
        lines += [
            f"- Mean annotators per tweet: {summary['annotators_per_tweet_mean']}",
            f"- Tweets with unanimous annotators: {summary['pct_unanimous']}%",
        ]
        lines += [f"- mean agreement, {k}: {v}" for k, v in summary["mean_agreement_by_class"].items()]
    lines += ["", "## Cleaning and duplicates", ""]
    lines += [f"- {k}: {v}" for k, v in summary["cleaning"].items()]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


def run_eda(cfg: dict) -> dict:
    df = load_raw(resolve_path(cfg["paths"]["raw_data"]))
    summary = compute_eda(df)
    figures = get_dir(cfg, "figures_dir")
    reports = get_dir(cfg, "reports_dir")
    plot_class_distribution(summary["class_counts"], figures / "class_distribution.png")
    plot_length_distribution(df["text"].str.split().str.len(), df["label"], figures / "length_distribution.png")
    write_report(summary, reports / "eda_summary.md")
    log.info("EDA written to %s and %s", reports / "eda_summary.md", figures)
    return summary


if __name__ == "__main__":
    try:
        result = run_eda(load_config())
    except FileNotFoundError as exc:
        log.error("%s", exc)
        sys.exit(1)
    for key, value in result.items():
        print(f"{key}: {value}")
